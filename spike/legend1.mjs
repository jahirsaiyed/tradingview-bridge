import { chromium } from "playwright-core";
const browser = await chromium.connectOverCDP("http://127.0.0.1:9222");
const page = browser.contexts()[0].pages().find(p => p.url().includes("tradingview.com/chart"));
await page.getByRole("button", { name: "Cancel", exact: true }).click().catch(e => console.log("no cancel:", e.message.split("\n")[0]));
await page.waitForTimeout(500);
await page.mouse.click(85, 125);
await page.waitForTimeout(1200);
const items = await page.evaluate(() => [...document.querySelectorAll('[data-name="legend-source-item"]')].map(e => e.innerText.replace(/\s+/g, " ").slice(0, 60)));
console.log(JSON.stringify(items, null, 1));
await page.screenshot({ path: "state.png" });
await browser.close();
