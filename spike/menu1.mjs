import { chromium } from "playwright-core";
const browser = await chromium.connectOverCDP("http://127.0.0.1:9222");
const page = browser.contexts()[0].pages().find(p => p.url().includes("tradingview.com/chart"));
await page.keyboard.press("Escape");
await page.waitForTimeout(800);
console.log("pine-dialog visible:", await page.locator('[data-name="pine-dialog"]').isVisible().catch(() => false));
await page.click('[data-name="pine-dialog"] button[title="More"]');
await page.waitForTimeout(600);
const items = await page.evaluate(() => [...document.querySelectorAll('[role="menuitem"]')].map((e, i) => ({ i, text: e.innerText.replace(/\s+/g, " ").trim(), tag: e.tagName, cls: (e.className || "").toString().slice(0, 40) })));
console.log(JSON.stringify(items, null, 1));
await page.screenshot({ path: "state.png" });
await browser.close();
