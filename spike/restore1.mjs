import { chromium } from "playwright-core";
const browser = await chromium.connectOverCDP("http://127.0.0.1:9222");
const page = browser.contexts()[0].pages().find(p => p.url().includes("tradingview.com/chart"));
await page.click('button[title="Move split-view to overlay"]');
await page.waitForTimeout(2500);
console.log("overlay dialog:", await page.locator('[data-name="pine-dialog"]').count(), "| split dialog:", await page.locator("#pine-editor-dialog").count());
const legend = await page.evaluate(() => [...document.querySelectorAll('[data-name="legend-source-item"]')].map(e => e.querySelector('[data-name="legend-source-title"]')?.innerText));
console.log("legend:", JSON.stringify(legend));
await page.screenshot({ path: "state.png" });
await browser.close();
